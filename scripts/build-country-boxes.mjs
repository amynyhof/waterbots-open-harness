/**
 * Builds src/lib/countryBoxes.generated.ts from Natural Earth's country file —
 * the maintainer's choice of 31 Oct 2026 on #167, so the Map tab can open on
 * the country the visitor told Wellington.
 *
 * Usage: node scripts/build-country-boxes.mjs <path to ne_110m_admin_0_countries.geojson>
 *
 * THE SOURCE is Natural Earth's 1:110m Admin 0 – Countries, v5.1.2, public
 * domain, from github.com/nvkelso/natural-earth-vector. The file itself is not
 * kept here: it is 839 kB, and all the site needs is each country's names and
 * the box around it. Its SHA-256 is written into the output, and this script
 * refuses any other file.
 *
 * THE BOX is the one around every part of the country. Where that box would
 * cross the 180° line (Fiji, Russia, Antarctica) it is the box around the
 * country's largest part instead, because a box across the whole world shows
 * nothing.
 *
 * A NAME THAT IS ALSO PART OF ANOTHER COUNTRY'S NAME IS DROPPED — "Sudan"
 * (South Sudan), "Guinea" (Papua New Guinea, Equatorial Guinea, Guinea-Bissau),
 * "Congo" (Democratic Republic of the Congo), "Cyprus" (Northern Cyprus). A
 * visitor who writes only that word may mean either, and the map never guesses
 * a place: it shows the whole world instead. The test is against the other
 * country's everyday names, not its formal one.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SHA256 = '6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f';
const OUT = 'src/lib/countryBoxes.generated.ts';

const path = process.argv[2];
if (!path) {
  console.error('Usage: node scripts/build-country-boxes.mjs <ne_110m_admin_0_countries.geojson>');
  process.exit(1);
}
const bytes = readFileSync(path);
const sha = createHash('sha256').update(bytes).digest('hex');
if (sha !== SHA256) {
  console.error(`FAILED — that file's SHA-256 is ${sha}, not Natural Earth v5.1.2's ${SHA256}.`);
  process.exit(1);
}

/** The same folding src/lib/placeBox.ts applies to what the visitor typed. */
const fold = (s) =>
  (s ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

const EVERYDAY = ['NAME', 'NAME_LONG', 'ADMIN', 'NAME_EN', 'BRK_NAME', 'NAME_SORT', 'NAME_ALT'];
const ALL = [...EVERYDAY, 'FORMAL_EN'];

const round = (n) => Math.round(n * 100) / 100;

function ringBox(ring) {
  const b = [180, 90, -180, -90];
  for (const [x, y] of ring) {
    b[0] = Math.min(b[0], x);
    b[1] = Math.min(b[1], y);
    b[2] = Math.max(b[2], x);
    b[3] = Math.max(b[3], y);
  }
  return b;
}
function ringArea(ring) {
  let s = 0;
  for (let i = 0; i < ring.length - 1; i++) s += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  return Math.abs(s / 2);
}

const { features } = JSON.parse(bytes.toString('utf8'));
const countries = features.map((f) => {
  const p = f.properties;
  const parts = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  let box = parts.map((part) => ringBox(part[0])).reduce((a, b) => [
    Math.min(a[0], b[0]),
    Math.min(a[1], b[1]),
    Math.max(a[2], b[2]),
    Math.max(a[3], b[3]),
  ]);
  if (box[2] - box[0] > 180) {
    const largest = parts.reduce((a, b) => (ringArea(b[0]) > ringArea(a[0]) ? b : a));
    box = ringBox(largest[0]);
  }
  return {
    name: p.NAME,
    everyday: [...new Set(EVERYDAY.map((k) => fold(p[k])).filter(Boolean))],
    names: [...new Set(ALL.map((k) => fold(p[k])).filter(Boolean))],
    box: box.map(round),
  };
});

const dropped = [];
const rows = countries.map((c) => {
  const kept = c.names.filter((n) => {
    const inside = countries.find(
      (o) => o !== c && o.everyday.some((m) => m !== n && ` ${m} `.includes(` ${n} `))
    );
    if (inside) dropped.push(`"${n}" (${c.name}), inside ${inside.name}'s name`);
    return !inside;
  });
  return { name: c.name, names: kept, box: c.box };
});

let out = `/**
 * GENERATED by scripts/build-country-boxes.mjs — do not edit by hand.
 *
 * Every country's names, folded to plain lower-case words, and the box around
 * it as [west, south, east, north] in degrees. Made from Natural Earth's
 * 1:110m Admin 0 – Countries, v5.1.2, public domain
 * (https://www.naturalearthdata.com), SHA-256 ${SHA256}.
 * Used only to open the map on the country a visitor named; nothing from it is
 * shown. ${rows.length} countries.
 *
 * Names dropped because they are part of another country's name:
${dropped.map((d) => ` *   ${d}`).join('\n')}
 */

export interface CountryBox {
  name: string;
  names: string[];
  box: [number, number, number, number];
}

export const COUNTRY_BOXES: CountryBox[] = [
`;
for (const r of rows) out += `  { name: ${JSON.stringify(r.name)}, names: ${JSON.stringify(r.names)}, box: ${JSON.stringify(r.box)} },\n`;
out += '];\n';
writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${rows.length} countries, ${dropped.length} names dropped.`);
