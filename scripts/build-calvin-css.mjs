/**
 * Writes src/styles/calvin.generated.css from the installed open core's
 * base stylesheet (@waterbots/core/base.css), every class scoped under
 * `.wb-calvin` — built 14 Nov 2026 with Calvin's install from calvin-v0.2.0.
 *
 * WHY A SCOPED COPY. The core's base.css is for a site without a design system
 * of its own. This site has one (the brand book), and several of the core's
 * class names are also this site's (.btn-primary, .t-caption, .eyebrow, .tag),
 * so importing it whole would restyle the rest of the site. Scoped, the core's
 * classes reach only the calculator, and its colour names are mapped to this
 * site's tokens by hand in src/styles/calvin.css. The core's :root token block
 * is left out on purpose: those values are the core's starting points, and
 * this site sets its own.
 *
 *   node scripts/build-calvin-css.mjs          # write it
 *   node scripts/build-calvin-css.mjs --check  # exit 1 if it would change, or a class the
 *                                              # screens use has no rule
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = join('node_modules', '@waterbots', 'core', 'dist', 'base.css');
const SCREENS = join('node_modules', '@waterbots', 'calvin', 'dist', 'screen.js');
const TARGET = join('src', 'styles', 'calvin.generated.css');
const SCOPE = '.wb-calvin';

const source = readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n');

/* Drop comments and the :where(:root) token block; keep one rule per line. */
const body = source
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/:where\(:root\)\s*\{[\s\S]*?\}/, '');

const rules = [];
for (const match of body.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const selectors = match[1]
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => `${SCOPE} ${s}`);
  if (!selectors.length) continue;
  rules.push(`${selectors.join(', ')} { ${match[2].trim()} }`);
}

const out = [
  '/* GENERATED by scripts/build-calvin-css.mjs from @waterbots/core/dist/base.css — do not edit.',
  '   Every class the core gives its screens, scoped under .wb-calvin so it reaches the calculator',
  '   and nothing else. The colour names are mapped to this site\'s tokens in calvin.css. */',
  '',
  ...rules,
  '',
].join('\n');

/* Every class the screens use must have a rule here, in the package's own
   print rules, or in this site's mapping file — or it would draw unstyled. */
function classesUsed() {
  const js = readFileSync(SCREENS, 'utf8');
  const found = new Set();
  for (const m of js.matchAll(/className:\s*(?:"([^"]*)"|`([^`]*)`)/g)) {
    const text = (m[1] ?? m[2] ?? '').replace(/\$\{[^}]*\}/g, ' ');
    for (const word of text.split(/\s+/)) if (/^[a-z][a-z0-9:-]*$/i.test(word)) found.add(word);
  }
  for (const m of js.matchAll(/"((?:btn-primary|border border-line text-fg-4|cursor-default)[^"]*)"/g)) {
    for (const word of m[1].split(/\s+/)) if (word) found.add(word);
  }
  return found;
}

const escape = (name) => name.replace(/:/g, '\\:');
const extra = existsSync(join('src', 'styles', 'calvin.css')) ? readFileSync(join('src', 'styles', 'calvin.css'), 'utf8') : '';
const printCss = readFileSync(join('node_modules', '@waterbots', 'calvin', 'dist', 'styles.css'), 'utf8');
const missing = [...classesUsed()].filter((name) => {
  const pattern = new RegExp(`\\.${escape(name).replace(/[\\]/g, '\\\\')}(?![a-zA-Z0-9_-])`);
  return !pattern.test(out) && !pattern.test(extra) && !pattern.test(printCss);
});

if (process.argv.includes('--check')) {
  const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n') : '';
  let failed = false;
  if (current !== out) {
    console.error(`${TARGET} is stale: run node scripts/build-calvin-css.mjs. The calculator would draw with an old copy of the core's classes.`);
    failed = true;
  }
  if (missing.length) {
    console.error(`The calculator uses classes no stylesheet defines: ${missing.join(', ')}`);
    failed = true;
  }
  if (failed) process.exit(1);
  console.log(`${TARGET} is current; every class the screens use has a rule.`);
} else {
  writeFileSync(TARGET, out);
  console.log(`Wrote ${TARGET} (${rules.length} rules).`);
  if (missing.length) console.log(`Classes with no rule yet: ${missing.join(', ')}`);
}
